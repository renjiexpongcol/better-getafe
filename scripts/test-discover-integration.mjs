import 'dotenv/config';
import test from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import fs from 'node:fs/promises';
import express from 'express';
import { activateDatabase } from '../server/src/services/cloudSql.js';
import { registerDestinationRoutes } from '../server/src/services/destinationRoutes.js';
import { saveDestination, listDestinations, findDestination, findLegacyDestination, deleteDestination } from '../server/src/repositories/destinationsRepository.js';
test('PostgreSQL destination lifecycle and public API isolation', { skip: process.env.RUN_DISCOVER_DB_TESTS !== '1' }, async () => {
 const pool = new pg.Pool(process.env.DATABASE_URL ? { connectionString: process.env.DATABASE_URL } : { host: process.env.DB_HOST || '127.0.0.1', port: Number(process.env.DB_PORT || 5432), database: process.env.DB_NAME || 'getafe_portal', user: process.env.DB_USER || 'getafe_app', password: process.env.DB_PASSWORD });
 const client = await pool.connect();
 let server;
 try {
  await client.query('BEGIN');
  const migration = await fs.readFile('database/migrations/postgresql/010_legacy_tourism_destinations.sql', 'utf8');
  await client.query(migration);
  await client.query('DROP TABLE legacy_destination_import');
  const aliases = await client.query('SELECT legacy_key, destination_id FROM destination_legacy_routes');
  assert.equal(aliases.rows.length, 5);
  const legacyId = aliases.rows.find(item => item.legacy_key === 'pandanon').destination_id;
  await client.query("UPDATE destinations SET full_description = 'Editorial changes must survive migration' WHERE id = $1", [legacyId]);
  await client.query(migration);
  await client.query('DROP TABLE legacy_destination_import');
  assert.equal((await client.query('SELECT full_description FROM destinations WHERE id = $1', [legacyId])).rows[0].full_description, 'Editorial changes must survive migration');

  // All fixture writes are rolled back; no public test content is committed.
  const execute = async (sql, params = []) => { let i = 0; const result = await client.query(sql.replace(/\?/g, () => `$${++i}`), params); return [result.rows, result] };
  activateDatabase('database', { execute, users: 0, pool: { end: async () => {} } });
  assert.equal(await findLegacyDestination('pandanon'), undefined);
  await client.query("UPDATE destinations SET published = TRUE, featured_image = '', slug = 'renamed-pandanon-test' WHERE id = $1", [legacyId]);
  assert.equal((await findLegacyDestination('pandanon')).slug, 'renamed-pandanon-test');
  await client.query('UPDATE destinations SET published = FALSE WHERE id = $1', [legacyId]);
  assert.equal(await findLegacyDestination('pandanon'), undefined);
  const base = { title: 'Destination test', slug: `test-discover-${Date.now()}`, shortDescription: 'Test only', fullDescription: 'Full content', featuredImage: '', imageAlt: '', location: '', category: '', published: false, featured: true, displayOrder: 99990 };
  const draft = await saveDestination(base);
  assert.equal(await findDestination(draft.slug), undefined);
  const published = [];
  for (let i = 0; i < 4; i++) published.push(await saveDestination({ ...base, slug: `${base.slug}-${i}`, published: true, displayOrder: i }));
  const featured = await listDestinations({ featured: true, limit: 3 });
  assert.equal(featured.items.length, 3);
  assert.deepEqual(featured.items.map(item => item.id), published.slice(0, 3).map(item => item.id));
  assert.equal((await findDestination(published[0].slug)).fullDescription, 'Full content');
  await saveDestination({ ...published[0], published: false }, published[0].id);
  assert.equal(await findDestination(published[0].slug), undefined);
  assert.equal(await deleteDestination(published[3].id), true);
  assert.equal(await deleteDestination('nonexistent'), false);
  const app = express(); app.use(express.json());
  registerDestinationRoutes(app, { admin: (_req, res) => res.sendStatus(401), permission: () => (_req, res) => res.sendStatus(403) });
  server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  assert.equal((await fetch(`${url}/api/admin/destinations`)).status, 401);
  assert.equal((await fetch(`${url}/api/admin/destinations/discover-danajon`)).status, 401);
  assert.equal((await fetch(`${url}/api/admin/destinations`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(base) })).status, 401);
  assert.equal((await fetch(`${url}/api/discover/${draft.slug}`)).status, 404);
  assert.equal((await fetch(`${url}/api/discover/legacy/pandanon`)).status, 404);
  assert.equal((await fetch(`${url}/api/discover/legacy/unknown`)).status, 404);
  await client.query('UPDATE destinations SET published = TRUE WHERE id = $1', [legacyId]);
  const legacyResponse = await fetch(`${url}/api/discover/legacy/pandanon`);
  assert.equal(legacyResponse.status, 200);
  assert.equal((await legacyResponse.json()).fullDescription, 'Editorial changes must survive migration');
  await client.query('UPDATE destinations SET published = FALSE WHERE id = $1', [legacyId]);
  const response = await fetch(`${url}/api/discover?featured=true&admin=true`);
  assert.equal(response.status, 200);
  assert.ok((await response.json()).items.every(item => item.published));
  activateDatabase('database', { execute: async () => { throw new Error('Simulated database failure') }, users: 0, pool: { end: async () => {} } });
  const failure = await fetch(`${url}/api/discover`);
  assert.equal(failure.status, 503);
  assert.equal((await failure.json()).error, 'Destination information is temporarily unavailable.');
 } finally { if (server) await new Promise(resolve => server.close(resolve)); await client.query('ROLLBACK'); client.release(); await pool.end() }
});
